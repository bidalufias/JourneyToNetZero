/**
 * Bundles the room edge function into a single Deno-ready file.
 *
 * Two things this solves.
 *
 * The function imports the same engine and reducer the tests exercise, from
 * `src/`. Deno will not resolve the extensionless relative imports those
 * modules use, and duplicating the reducer into the function directory would
 * let the deployed game and the tested game drift apart, the one failure this
 * project cannot afford. So we bundle rather than copy.
 *
 * And the content pack has to reach the server without ever reaching a client.
 * It carries every option's effects, so it cannot be fetched from a public URL
 * and it cannot ship in the browser bundle. It lives only where the engine
 * does, embedded in the function.
 *
 * Both outputs are deliberately left readable rather than minified or
 * base64'd. They are moved by hand often enough, pasted into the Supabase
 * dashboard or posted to the Management API, that being able to diff and
 * checksum them matters more than the extra kilobytes, and Deno does not care
 * either way.
 */
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

// The handwritten source lives outside the deploy directory: Supabase's CLI
// treats `functions/<name>/index.ts` as the entrypoint, and Deno cannot resolve
// that file's extensionless imports into `src/`. So the bundle *is* index.ts.
const SRC = 'supabase/functions/_src/room.ts'
const DIR = 'supabase/functions/room'
const OUT = `${DIR}/index.ts`
mkdirSync(DIR, { recursive: true })

// ── 1. Embed the content pack, compressed ──────────────────────────────────

const pack = JSON.parse(readFileSync('content/jtnz-content-pack-v2.json', 'utf8'))
const tips = JSON.parse(readFileSync('content/jtnz-insider-tips.json', 'utf8'))
const merged = { ...pack, insiderTips: { ...pack.insiderTips, ...tips } }

const raw = Buffer.from(JSON.stringify(merged), 'utf8')

writeFileSync(
  'supabase/functions/room/content.gen.ts',
  '// GENERATED by tools/build-function.mjs. Do not edit.\n' +
    '// The content pack, embedded so the edge function is self-contained and the\n' +
    '// option effects never reach anywhere a client could read them.\n' +
    `export const PACK = ${JSON.stringify(merged, null, 0)} as const\n`,
)

// ── 2. Bundle ──────────────────────────────────────────────────────────────

await build({
  entryPoints: [SRC],
  outfile: OUT,
  bundle: true,
  format: 'esm',
  target: 'esnext',
  platform: 'neutral',
  // The content pack stays a separate file rather than being inlined: it is a
  // single opaque base64 literal, and keeping it out of the code bundle means
  // each deployed file can be checksummed independently. Deno resolves the
  // explicit .ts extension fine.
  // Left unresolved on purpose: esbuild emits the import verbatim and the file
  // is written next to the output, so Deno loads it at runtime.
  external: ['./content.gen.ts'],
  minify: false,
  banner: {
    js:
      '// GENERATED by tools/build-function.mjs. Do not edit.\n' +
      '// Source: supabase/functions/_src/room.ts plus src/engine and src/game.\n' +
      '// Rebuild with `npm run build:function`.\n',
  },
  logLevel: 'info',
})

const size = readFileSync(OUT).length
console.log(
  `bundled -> ${OUT} (${(size / 1024).toFixed(1)} kB code, ${(raw.length / 1024).toFixed(0)} kB content pack)`,
)
